/**
 * Writes src/generated-reexports.ts: explicit named re-exports of everything
 * @hackpsu/api-client exposes.
 *
 * The barrel cannot simply `export * from "@hackpsu/api-client"`. This package
 * carries a "use client" directive for its providers, and Next rejects a star
 * re-export inside a client boundary:
 *
 *   It's currently unsupported to use "export *" in a client boundary.
 *
 * Naming every export sidesteps that while keeping one import for consumers.
 * The list comes from the client's own export statement, so it cannot drift.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dts = resolve(here, "../../api-client/dist/index.d.ts");
const out = resolve(here, "../src/generated-reexports.ts");

const source = readFileSync(dts, "utf8");

const values = new Set();
const types = new Set();

// The emitted declaration ends with one export statement listing every public
// name, with `type ` marking the type-only ones.
for (const block of source.matchAll(/export\s*\{([\s\S]*?)\}/g)) {
  for (const raw of block[1].split(",")) {
    const entry = raw.trim();
    if (!entry) continue;
    const name = entry.split(/\s+as\s+/).pop().trim();
    if (entry.startsWith("type ")) types.add(name.replace(/^type\s+/, ""));
    else values.add(name);
  }
}

if (values.size + types.size === 0) {
  throw new Error(
    `Found no exports in ${dts}. Build @hackpsu/api-client before this script.`,
  );
}

const list = (names) =>
  [...names].sort().map((n) => `  ${n},`).join("\n");

const body = `// Generated by scripts/generate-reexports.mjs. Do not edit.
// Named rather than star re-exports because Next forbids \`export *\` inside a
// "use client" boundary, which this package declares for its providers.

export {
${list(values)}
} from "@hackpsu/api-client";

export type {
${list(types)}
} from "@hackpsu/api-client";
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, body);
console.log(
  `wrote ${out}: ${values.size} values, ${types.size} types`,
);
